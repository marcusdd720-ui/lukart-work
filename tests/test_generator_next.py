"""Synthetic end-to-end and adversarial coverage for the new drafting candidate."""
from dataclasses import replace
from datetime import date
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

from lukart_work.contracts.messages import SnapshotMember
from lukart_work.generator_next.demo import synthetic_case
from lukart_work.generator_next.service import (
    CATALOGUE, CodeIdentity, propose, verify_candidate, write_candidate,
)
from lukart_work.validation.rules import Violation, digest, ref, validate_graph, validate_state


def rebound(view, records):
    heads = {}
    for item in records:
        key = (item.kind, item.id)
        if key not in heads or item.revision > heads[key].revision:
            heads[key] = ref(item)
    snapshot = view.snapshot.model_copy(update={
        "members": tuple(SnapshotMember(ref=ref(item), content_hash=digest(item)) for item in records),
        "heads": tuple(heads.values())})
    target = view.acceptance.snapshot_target.model_copy(update={"snapshot_hash": digest(snapshot)})
    return replace(view, records=tuple(records), snapshot=snapshot,
                   acceptance=view.acceptance.model_copy(update={"snapshot_target": target}))


class GeneratorNextTests(unittest.TestCase):
    def setUp(self):
        self.view, self.intake = synthetic_case()

    def mutate_kind(self, kind, **changes):
        return rebound(self.view, [item.model_copy(update=changes) if item.kind == kind else item
                                   for item in self.view.records])

    def assert_denied(self, code, view=None, intake=None):
        with self.assertRaisesRegex(Violation, code):
            propose(view or self.view, intake or self.intake)

    def test_three_document_types_use_their_own_required_fields(self):
        for kind in CATALOGUE:
            with self.subTest(kind=kind):
                view, intake = synthetic_case(kind)
                records = validate_graph(view.records, {item.id: item for item in view.snapshot.sources})
                for item in view.records:
                    validate_state(item, records)
                proposal = propose(view, intake)
                self.assertIn(CATALOGUE[kind][0], proposal.text)
                self.assertEqual(len(proposal.trace), len(CATALOGUE[kind][1]) + 1)
                self.assertIn("NO_FINAL_RELEASE", proposal.risks)
                self.assertNotIn("Generated by", proposal.text)
                self.assertNotIn("REVIEW_REQUIRED", proposal.text)

    def test_wrong_type_rejected(self):
        self.assert_denied("DOCUMENT_TYPE_UNSUPPORTED", intake=replace(self.intake, document_type="court"))

    def test_missing_or_unknown_type_field_rejected(self):
        self.assert_denied("TYPE_FIELDS_MISSING_OR_UNKNOWN", intake=replace(self.intake, fields={}))
        fields = dict(self.intake.fields, invented=next(iter(self.intake.fields.values())))
        self.assert_denied("TYPE_FIELDS_MISSING_OR_UNKNOWN", intake=replace(self.intake, fields=fields))

    def test_real_jurisdiction_rejected(self):
        self.assert_denied("SYNTHETIC_ONLY", self.mutate_kind("Case", jurisdiction="PL"))

    def test_snapshot_bytes_tampering_rejected(self):
        records = tuple(item.model_copy(update={"statement": "changed"}) if item.kind == "Fact" else item
                        for item in self.view.records)
        self.assert_denied("INVALID_HASH", replace(self.view, records=records))

    def test_source_bytes_tampering_rejected(self):
        blobs = dict(self.view.sources)
        blobs[next(iter(blobs))] += b"!"
        self.assert_denied("SOURCE_BYTES_MISMATCH", replace(self.view, sources=blobs))

    def test_missing_source_rejected(self):
        blobs = dict(self.view.sources)
        blobs.pop(next(iter(blobs)))
        self.assert_denied("SOURCE_SET", replace(self.view, sources=blobs))

    def test_duplicate_revision_rejected(self):
        self.assert_denied("DUPLICATE_REVISION", replace(self.view,
            records=(*self.view.records, self.view.records[0])))

    def test_snapshot_approval_is_exact(self):
        target = self.view.acceptance.snapshot_target.model_copy(update={"snapshot_hash": "0" * 64})
        self.assert_denied("SNAPSHOT_APPROVAL_MISMATCH", replace(self.view,
            acceptance=self.view.acceptance.model_copy(update={"snapshot_target": target})))

    def test_no_automatic_candidate_promotion(self):
        self.assert_denied("CONFIRMED_CURRENT_FACT_REQUIRED", self.mutate_kind("Fact", status="CANDIDATE"))

    def test_disputed_evidence_rejected(self):
        self.assert_denied("ACCEPTED_EVIDENCE_REQUIRED", self.mutate_kind("Evidence", authenticity="DISPUTED"))

    def test_revoked_fact_acceptance_rejected(self):
        records = [item.model_copy(update={"status": "REVOKED"})
            if item.kind == "Decision" and item.decision_type == "FACT_ACCEPTANCE" else item
            for item in self.view.records]
        self.assert_denied("HUMAN_APPROVAL_REQUIRED", rebound(self.view, records))

    def test_ai_cannot_replace_human_acceptance(self):
        records = [item.model_copy(update={"decided_by": item.decided_by.model_copy(update={"kind": "AI"})})
            if item.kind == "Decision" else item for item in self.view.records]
        self.assert_denied("HUMAN_REQUIRED", rebound(self.view, records))

    def test_rehashed_snapshot_cannot_bypass_native_legal_pin_integrity(self):
        records = [item.model_copy(update={"registry_pin": item.registry_pin.model_copy(
            update={"content_hash": "0" * 64})}) if item.kind == "LegalSource" else item
            for item in self.view.records]
        self.assert_denied("INVALID_HASH", rebound(self.view, records))

    def test_native_predecessor_approval_and_content_binding(self):
        records = [item.model_copy(update={"statement": "Changed after review"})
            if item.kind == "Fact" and item.status == "CONFIRMED" else item
            for item in self.view.records]
        self.assert_denied("APPROVAL_CONTENT_CHANGED", rebound(self.view, records))
        confirmed = next(item for item in self.view.records if item.kind == "Fact" and item.status == "CONFIRMED")
        records = [item.model_copy(update={"targets": (ref(confirmed),)})
            if ref(item) == confirmed.acceptance else item for item in self.view.records]
        self.assert_denied("HUMAN_APPROVAL_REQUIRED", rebound(self.view, records))

    def test_historical_fact_cannot_be_selected_as_current(self):
        historical = next(item for item in self.view.records if item.kind == "Fact" and item.status == "REVIEWED")
        fields = {key: ref(historical) if target.id == historical.id else target
                  for key, target in self.intake.fields.items()}
        self.assert_denied("CONFIRMED_CURRENT_FACT_REQUIRED", intake=replace(self.intake, fields=fields))

    def test_expired_or_wrong_jurisdiction_rule_rejected(self):
        self.assert_denied("LEGAL_APPLICABILITY_UNKNOWN", intake=replace(self.intake, evaluation_date=date(2027, 1, 1)))
        self.assert_denied("LEGAL_APPLICABILITY_UNKNOWN", self.mutate_kind("LegalRule", jurisdiction="PL"))

    def test_wrong_document_type_rule_rejected(self):
        self.assert_denied("LEGAL_APPLICABILITY_UNKNOWN", self.mutate_kind("LegalRule", applicable_document_types=()))

    def test_withdrawn_legal_source_rejected(self):
        self.assert_denied("LEGAL_SOURCE_INVALID", self.mutate_kind("LegalSource", status="RETRACTED"))

    def test_untraceable_fact_rejected_after_valid_snapshot_rehash(self):
        self.assert_denied("SOURCE_LOCATOR_OR_LITERAL_MISMATCH", self.mutate_kind("Fact", statement="Invented event"))

    def test_formal_missing_data_rejected(self):
        self.assert_denied("FORMAL_INPUT_MISSING", intake=replace(self.intake, recipient=" "))

    def test_export_is_fresh_hash_checked_and_restart_verifiable(self):
        proposal = propose(self.view, self.intake)
        with tempfile.TemporaryDirectory() as tmp:
            output = Path(tmp) / "candidate"
            write_candidate(proposal, output, identity=CodeIdentity("a" * 40, "b" * 64, "UNCOMMITTED"))
            self.assertEqual(verify_candidate(output, expected_input_hash=proposal.input_hash,
                             identity=CodeIdentity("a" * 40, "b" * 64, "UNCOMMITTED"))["files_checked"], 4)
            # A separate process reads disk state; no in-memory approval is reused.
            code = ("from pathlib import Path; from lukart_work.generator_next.service import verify_candidate, CodeIdentity; "
                    "import sys; print(verify_candidate(Path(sys.argv[1]), expected_input_hash=sys.argv[2], identity=CodeIdentity(sys.argv[3], 'b'*64, 'UNCOMMITTED'))['result'])")
            completed = subprocess.run([sys.executable, "-B", "-c", code, str(output), proposal.input_hash, "a" * 40],
                                       capture_output=True, text=True, check=True)
            self.assertIn("BYTE_INTEGRITY_ONLY", completed.stdout)
            with self.assertRaises(FileExistsError):
                write_candidate(proposal, output, identity=CodeIdentity("a" * 40, "b" * 64, "UNCOMMITTED"))
            (output / "document.md").write_text("tampered", encoding="utf-8")
            with self.assertRaisesRegex(Violation, "ARTIFACT_TAMPERED"):
                verify_candidate(output, expected_input_hash=proposal.input_hash, identity=CodeIdentity("a" * 40, "b" * 64, "UNCOMMITTED"))

    def test_manifest_wrong_pin_or_traversal_rejected(self):
        proposal = propose(self.view, self.intake)
        with tempfile.TemporaryDirectory() as tmp:
            output = Path(tmp) / "candidate"
            write_candidate(proposal, output, identity=CodeIdentity("a" * 40, "b" * 64, "UNCOMMITTED"))
            with self.assertRaisesRegex(Violation, "MANIFEST_BINDING_MISMATCH"):
                verify_candidate(output, expected_input_hash=proposal.input_hash, identity=CodeIdentity("b" * 40, "b" * 64, "UNCOMMITTED"))
            manifest = json.loads((output / "manifest.json").read_text(encoding="utf-8"))
            manifest["files"]["../outside"] = {"bytes": 1, "sha256": "a" * 64}
            (output / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
            with self.assertRaisesRegex(Violation, "PACKAGE_MEMBER_SET"):
                verify_candidate(output, expected_input_hash=proposal.input_hash, identity=CodeIdentity("a" * 40, "b" * 64, "UNCOMMITTED"))

    def test_preview_escapes_html(self):
        proposal = propose(self.view, replace(self.intake, sender="<script>alert(1)</script>"))
        with tempfile.TemporaryDirectory() as tmp:
            preview = write_candidate(proposal, Path(tmp) / "candidate", identity=CodeIdentity("a" * 40, "b" * 64, "UNCOMMITTED"))
            self.assertNotIn("<script>", preview.read_text(encoding="utf-8"))
            self.assertIn("&lt;script&gt;", preview.read_text(encoding="utf-8"))


if __name__ == "__main__":
    unittest.main()

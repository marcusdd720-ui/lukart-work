"""Dependency inversion boundaries for the modular monolith. No adapter implementation."""
from typing import Protocol
from uuid import UUID
from lukart_work.domain.models import Actor, Entity, Ref, VersionPin
from lukart_work.contracts.messages import Snapshot, SourceDocument, ValidationRun, AIRequest, AIResult, SemanticDocument

class AuthorizationPort(Protocol):
    def require(self, actor: Actor, tenant_id: UUID, case_id: UUID, action: str) -> None: ...

class CaseRepository(Protocol):
    def get_revision(self, tenant_id: UUID, case_id: UUID, target: Ref) -> Entity: ...
    def get_heads(self, tenant_id: UUID, case_id: UUID) -> tuple[int, tuple[Ref, ...]]: ...
    def get_snapshot(self, tenant_id: UUID, case_id: UUID, snapshot_id: UUID) -> Snapshot: ...

class SourceDocumentPort(Protocol):
    def get(self, tenant_id: UUID, case_id: UUID, document_id: UUID) -> SourceDocument: ...
    def verify_bytes(self, tenant_id: UUID, case_id: UUID, document_id: UUID, expected_hash: str) -> bool: ...

class ValidationProvider(Protocol):
    def validate(self, tenant_id: UUID, case_id: UUID, draft: Ref, snapshot: Snapshot, policy: VersionPin) -> ValidationRun: ...

class ModelProvider(Protocol):
    """Trusted drafting adapter; the application validates both payload and execution attestation."""
    def propose(self, request: AIRequest) -> AIResult: ...


class AttestedDraftingProvider(Protocol):
    def propose(self, invocation) -> AIResult: ...
    def execution_receipt(self, request_id: UUID): ...

class DocumentProvider(Protocol):
    def build_semantic_document(self, tenant_id: UUID, case_id: UUID, draft: Ref, snapshot: Snapshot) -> SemanticDocument: ...

class KnowledgeProvider(Protocol):
    def resolve(self, pin: VersionPin) -> bytes: ...

class ReasoningProvider(Protocol):
    def analyze(self, request: AIRequest) -> AIResult: ...

class EvidenceProvider(SourceDocumentPort, Protocol):
    pass
